      character(len=30)  :: cstr_volcname
      character(len=30)  :: cstr_run_date
      character(len=30)  :: cstr_windfile
      character(len=40)  :: cstr_ErStartT
      character(len=27)  :: cstr_ErHeight
      character(len=30)  :: cstr_ErDuratn
      character(len=38)  :: cstr_ErVolume
      character(len=45)  :: cstr_note

      character(len=10)  :: filename_root
      character(len=14)  :: filename_script
      character(len=14)  :: filename_outdata
      character(len=14)  :: filename_png
      integer            :: fid_script   = 55
      integer            :: fid_outdata  = 54
      character(len=27)  :: coord_str
      character(len=80)  :: plotcom
      integer            :: i,k
      integer            :: iostatus
      integer            :: cstat
      character(len=120) :: iomessage
      integer            :: iw,iwf
      character(len= 80) :: linebuffer080
      character(len=130) :: linebuffer130
      character(len=200) :: cmd

      ! Plotting variables

      real(kind=ip) :: tmin    , zmin    , cmin      ! graph minima
      real(kind=ip) :: tmax    , zmax    , cmax      ! graph maxima
      real(kind=ip) :: tlab1   , zlab1   , clab1     ! graph first label
      real(kind=ip) :: tlabstep, zlabstep, clabstep  ! graph label increment
      real(kind=ip) :: cloudcon_thresh_mgm3

      ! Gnuplot variables

      INTERFACE
        character (len=20) function HS_xmltime(HoursSince,byear,useLeaps)
          implicit none
          !implicit none (type, external)
          integer        ,parameter  :: dp        = 8  ! double precision
          real(kind=dp)  ,intent(in) :: HoursSince
          integer        ,intent(in) :: byear
          logical        ,intent(in) :: useLeaps
        end function HS_xmltime
      END INTERFACE

      do io=1,2;if(VB(io).le.verbosity_debug1)then
        write(outlog(io),*)"     Entered Subroutine write_2Dprof_PNG_gnuplot"
      endif;enddo

      ! Test for icon file
      inquire( file=trim(adjustl(Instit_IconFile)), exist=HaveIconFile)

      ! Build strings with run info for legend
      ! Volcano:     Erup.start:
      ! Run date:    Plm Height:
      ! Windfile:    Duration:
      !              Volume:
      write(cstr_volcname,'(a10,a20)')'Volcano:  ' ,VolcanoName
      write(cstr_run_date,'(a10,a20)')'Run Date: ',os_time_log
      read(cdf_b3l1,*,iostat=iostatus,iomsg=iomessage) iw,iwf
      write(cstr_windfile,'(a10,i5)')'Windfile: ',iwf
      if(neruptions.gt.1)then
        write(cstr_note,'(a45)')'WARNING: Multiple eruptions, only first given'
      else
        write(cstr_note,'(a1)')" "
      endif

      !e_StartTime,e_PlumeHeight,e_Duration,e_Volume
      write(cstr_ErStartT,'(a20,a20)')'Erup. Start Time:   ',&
            HS_xmltime(SimStartHour+e_StartTime(1),BaseYear,useLeap)
      write(cstr_ErHeight,'(a20,f4.1,a3)')'Erup. Plume Height: ',e_PlumeHeight(1),' km'
      write(cstr_ErDuratn,'(a20,f4.1,a6)')'Erup. Duration:     ',e_Duration(1),' hours'
      write(cstr_ErVolume,'(a20,f8.5,a10)')'Erup. Volume:       ',e_Volume(1),' km3 (DRE)'

      write(filename_root,52)vprof_ID
 52   format('vprof_',i4.4)
      filename_outdata = trim(adjustl(filename_root)) // ".dat"
      filename_script  = trim(adjustl(filename_root)) // ".gpi"
      filename_png     = trim(adjustl(filename_root)) // ".png"

      ! Get min/max and label interval for all three axies.
      tmin=real(0,kind=ip)
      tmax=real(ceiling(time_native(ntmax)),kind=ip)
      tlab1    = 0.0_ip
      if(tmax.gt.240.0_ip)then
        tlabstep = 48.0_ip
      elseif(tmax.gt.120.0_ip)then
        tlabstep = 24.0_ip
      elseif(tmax.gt.30.0_ip)then
        tlabstep = 10.0_ip
      elseif(tmax.gt.15.0_ip)then
        tlabstep = 5.0_ip
      elseif(tmax.gt.6.0_ip)then
        tlabstep = 2.0_ip
      else
        tlabstep = 1.0_ip
      endif

      zmin=real(0,kind=ip)
      zmax=real(z_cc_pd(nzmax),kind=ip)
      zlab1    = 0.0_ip
      if(zmax.gt.30.0_ip)then
        zlabstep = 10.0_ip
      elseif(zmax.gt.15.0_ip)then
        zlabstep = 5.0_ip
      elseif(zmax.gt.6.0_ip)then
        zlabstep = 2.0_ip
      else
        zlabstep = 1.0_ip
      endif

      cloudcon_thresh_mgm3 = CLOUDCON_THRESH * KG_2_MG / KM3_2_M3  ! convert from kg/km3 to mg/m3
      cmin=real(0,kind=ip)
      cmax=real(maxval(pr_ash(:,:,vprof_ID)),kind=ip)    ! Get the max value for this profile
      cmin=real(min(cmin,cloudcon_thresh_mgm3),kind=ip)  ! Do not let cmax drop below the threshold
      if    (cmax.gt.4.0e4_ip)then
          clabstep = 5.0e3_ip
      elseif(cmax.gt.1.0e4_ip)then
          clabstep = 2.0e3_ip
      elseif(cmax.gt.4.0e3_ip)then
          clabstep = 5.0e2_ip
      elseif(cmax.gt.1.0e3_ip)then
          clabstep = 2.0e2_ip
      elseif(cmax.gt.4.0e2_ip)then
          clabstep = 5.0e1_ip
      elseif(cmax.gt.1.0e2_ip)then
          clabstep = 2.0e1_ip
      elseif(cmax.gt.4.0e1_ip)then
          clabstep = 5.0e0_ip
      elseif(cmax.gt.1.0e1_ip)then
          clabstep = 2.0e0_ip
      elseif(cmax.gt.1.0e0_ip)then
          clabstep = 5.0e-1_ip
      else
          clabstep = 1.0e-1_ip
      endif
      clab1    = 0.0_ip

      ! Prep data: gnuplot will load x y z data in column format
      open(unit=fid_outdata,file=filename_outdata,status='replace')
      do i = 1,ntmax
        do k = 1,nzmax
          write(fid_outdata,*)time_native(i),z_cc_pd(k),pr_ash(k,i,vprof_ID)
        enddo
        write(fid_outdata,*)""
      enddo
      close(fid_outdata)

      ! Build the plot title
      if(IsLatLon)then
        write(coord_str,101)x_vprofile(vprof_ID),y_vprofile(vprof_ID)
      else
        write(coord_str,102)x_vprofile(vprof_ID),y_vprofile(vprof_ID)
      endif
 101  format(' (lon=',f7.2,', lat=',f6.2,')')
 102  format(' (x=',f9.3,', y=',f9.3,')')
      write(title_plot,*)trim(adjustl(Site_vprofile(vprof_ID))),coord_str

      ! Set up to plot via gnuplot script
      open(unit=fid_script,file=filename_script,status='replace')
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"# Temporary gnuplot script for producing vertical profiles for Ash3d_PostProc"
      write(fid_script,'(g0)')"# Adjust to suit your needs."
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"set terminal pngcairo font 'sans,12' size 854,603"   ! Set the image size
      linebuffer080 = "set output '" // filename_png // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
      if(HaveIconFile)then
        write(fid_script,'(g0)')"set multiplot"
        write(fid_script,'(g0)')" "
        write(fid_script,'(g0)')"# Set logo plot"
        write(fid_script,'(g0)')"set size 0.2, 0.2"
        write(fid_script,'(g0)')"set origin 0.78, 0.0"
        write(fid_script,'(g0)')"unset key"
        write(fid_script,'(g0)')"unset tics"
        write(fid_script,'(g0)')"unset xlabel"
        write(fid_script,'(g0)')"unset ylabel"
        write(fid_script,'(g0)')"unset title"
        write(fid_script,'(g0)')"#unset border"
        write(fid_script,'(g0)')"unset label"
        write(fid_script,'(g0)')"set size ratio -1"
        linebuffer080 = 'plot "' // trim(adjustl(Instit_IconFile)) // '" binary filetype=png with rgbalpha'
        write(fid_script,'(g0)')trim(adjustl(linebuffer080))
        write(fid_script,'(g0)')" "
      else
        do io=1,2;if(VB(io).le.verbosity_info)then
          write(outlog(io),*)"Institution Logo not found."
          write(outlog(io),*)"If you would like your logo on these maps, copy a"
          write(outlog(io),*)"small image (130x50) to ASH3DHOME/share/post_proc/logo.png"
        endif;enddo
      endif

      write(fid_script,'(g0)')"set origin 0, .15"
      write(fid_script,'(g0)')"set size 0.85, 0.9"              ! Set x and y scale for plot
      write(fid_script,'(g0)')"set size ratio 0.75"
      write(fid_script,'(g0)')"set tics"
      linebuffer080 = "set ylabel '" // trim(adjustl(cstr_ylabel)) // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
      linebuffer080 = "set xlabel '" // trim(adjustl(cstr_xlabel)) // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
      linebuffer080 = "set title '" // trim(adjustl(title_plot)) // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
      write(fid_script,'(g0)')"set isosamples 50"
      write(fid_script,'(g0)')"set pm3d"
      write(fid_script,'(g0)')"set palette cubehelix negative"
      write(fid_script,'(g0)')"unset surface"
      write(fid_script,'(g0)')"set view map"
      write(fid_script,'(g0)')"set key off"

      write(fid_script,'(g0)')"XMIN = 0.0"
      write(fid_script,'(g0)')"YMIN = 0.0"
      write(fid_script,'(a7,f10.4)')"XMAX = ",time_native(ntmax)
      write(fid_script,'(a7,f10.4)')"YMAX = ",z_cc_pd(nzmax)
      write(fid_script,'(g0)')"XVAL = -XMAX*0.2"
      write(fid_script,'(g0)')"YVAL = -YMAX*0.35"

      linebuffer130 = "set label '" // trim(adjustl(cstr_volcname)) // "' at XVAL, YVAL font 'sans,9' offset character 0,2"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      linebuffer130 = "set label '" // trim(adjustl(cstr_run_date)) // "' at XVAL, YVAL font 'sans,9' offset character 0,1"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      linebuffer130 ="set label '" // trim(adjustl(cstr_windfile)) // "' at XVAL, YVAL font 'sans,9' offset character 0,0"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      if(neruptions.gt.1)then
        linebuffer130 = "set label '" // trim(adjustl(cstr_note)) // "' at XVAL, YVAL font 'sans,9' offset character 0,-1"
        write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      endif

      write(fid_script,'(g0)')"XVAL = XMIN+(XMAX-XMIN)*0.4"
      linebuffer130 = "set label '" // trim(adjustl(cstr_ErStartT)) // "' at XVAL, YVAL font 'sans,9' offset character 0,2"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      linebuffer130 = "set label '" // trim(adjustl(cstr_ErHeight)) // "' at XVAL, YVAL font 'sans,9' offset character 0,1"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      linebuffer130 = "set label '" // trim(adjustl(cstr_ErDuratn)) // "' at XVAL, YVAL font 'sans,9' offset character 0,0"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      linebuffer130 = "set label '" // trim(adjustl(cstr_ErVolume)) // "' at XVAL, YVAL font 'sans,9' offset character 0,-1"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))

      linebuffer080 = "set cblabel '" // trim(adjustl(cstr_zlabel)) // "'"
      write(fid_script,'(g0)')linebuffer080
      !write(fid_script,*)"set cblabel 'Ash con. in mg/m3'"
      linebuffer080 = "splot '" // filename_outdata // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
      if(HaveIconFile)then
        ! If we are including a logo via multiplot, close out multiplot environment
        write(fid_script,'(g0)')"unset multiplot"
      endif

      close(fid_script)

      write(plotcom,'(a11,a14)')'gnuplot -p ',filename_script
      call execute_command_line(plotcom,&
                                wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)
      ! Clean up
      if (CleanScripts_gnuplot) then
        cmd = "rm -f vprof_*dat vprof_*gpi"
        do io=1,2;if(VB(io).le.verbosity_info)then
          write(outlog(io),*)"Cleaning up temporary files with command:"
          write(outlog(io),*)trim(adjustl(cmd))
        endif;enddo
        call execute_command_line(trim(adjustl(cmd)),&
                                  wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)
      endif

      do io=1,2;if(VB(io).le.verbosity_debug1)then
        write(outlog(io),*)"     Exited Subroutine write_2Dprof_PNG_gnuplot"
      endif;enddo

      return

      end subroutine write_2Dprof_PNG_gnuplot

!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
!
!  write_DepPOI_TS_PNG_gnuplot
!
!  Called from: Ash3d_PostProc.f90
!  Arguments:
!    pt_indx       = index of point in Ash3d netcdf output file
!
!  This subroutine creates a png plot of the transient deposit accumulation at
!  the airport/POI given by pt_index using the gnuplot graphics package.
!
!  To invoke:
!   ASH3DPLOT=3 ./Ash3d_PostProc 3d_tephra_fall.nc 8 2
!
!   Example script:
!     ##########################################################################
!     # Temporary gnuplot script for producing deposit time-series plots for Ash3d_PostProc
!     # Adjust to suit your needs.
!     ##########################################################################
!     set terminal png size 400,300
!     set key bmargin left horizontal Right noreverse enhanced autotitles box linetype -1 linewidth 1.000
!     set border 31 lw 2.0 lc rgb '#000000'
!     set style line 1 linecolor rgbcolor '#888888' linewidth 2.0 pt 7
!     set ylabel 'Deposit Thickeness (mm)'
!     set xlabel 'Time (hours after eruption)'
!     set nokey
!     set output 'depTS_0001.png'
!     set title 'Cuernavaca, Mexico                 '
!     plot [0:   25][0:  1] 'depTS_0001.dat' with filledcurve x1 ls 1
!
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

      subroutine write_DepPOI_TS_PNG_gnuplot(pt_indx)

      use Output_Vars,   only : &
         THICKNESS_THRESH

      use Airports,      only : &
         Airport_Name,Airport_Thickness_TS

      use io_data,       only : &
         nWriteTimes,WriteTimes

      use time_data,     only : &
         Simtime_in_hours

      integer,intent(in) :: pt_indx

      real(kind=dp) :: ymaxpl
      character(len=10) :: filename_root
      character(len=14) :: filename_script
      character(len=14) :: filename_outdata
      character(len=14) :: filename_png
      integer           :: fid_outdata  = 54
      integer           :: fid_script  = 55
      integer           :: i
      character(len=25) :: plotcom
      integer           :: iostatus
      integer           :: cstat
      character(len=120):: iomessage
      character(len=200):: cmd
      character(len= 80):: linebuffer080
      character(len=130):: linebuffer130

      integer,save      :: plot_index = 0

      do io=1,2;if(VB(io).le.verbosity_debug1)then
        write(outlog(io),*)"     Entered Subroutine write_DepPOI_TS_PNG_gnuplot"
      endif;enddo

      if(Airport_Thickness_TS(pt_indx,nWriteTimes).lt.THICKNESS_THRESH)then
        return
      else
        plot_index = plot_index + 1
      endif

      write(filename_root,52)plot_index
 52   format('depTS_',i4.4)
      filename_outdata = trim(adjustl(filename_root)) // ".dat"
      filename_script  = trim(adjustl(filename_root)) // ".gpi"
      filename_png     = trim(adjustl(filename_root)) // ".png"

      open(unit=fid_outdata,file=filename_outdata,status='replace')
      do i = 1,nWriteTimes
        write(fid_outdata,*)WriteTimes(i),Airport_Thickness_TS(pt_indx,i)
      enddo
      close(fid_outdata)

      if(Airport_Thickness_TS(plot_index,nWriteTimes).lt.THICKNESS_THRESH)then
        ymaxpl = 1.0_dp
      elseif(Airport_Thickness_TS(plot_index,nWriteTimes).lt.1.0_dp)then
        ymaxpl = 1.0_dp
      elseif(Airport_Thickness_TS(plot_index,nWriteTimes).lt.5.0_dp)then
        ymaxpl = 5.0_dp
      elseif(Airport_Thickness_TS(plot_index,nWriteTimes).lt.25.0_dp)then
        ymaxpl = 25.0_dp
      else
        ymaxpl = 100.0_dp
      endif

      ! Set up to plot via gnuplot script
      open(unit=fid_script,file=filename_script,status='replace')
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"# Temporary gnuplot script for producing deposit time-series plots for Ash3d_PostProc"
      write(fid_script,'(g0)')"# Adjust to suit your needs."
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"set terminal png size 400,300"
      linebuffer130 = "set key bmargin left horizontal Right noreverse enhanced " // &
                              "autotitles box linetype -1 linewidth 1.000"
      write(fid_script,'(g0)')trim(adjustl(linebuffer130))
      write(fid_script,'(g0)')"set border 31 lw 2.0 lc rgb '#000000'"
      write(fid_script,'(g0)')"set style line 1 linecolor rgbcolor '#888888' linewidth 2.0 pt 7"
      write(fid_script,'(g0)')"set ylabel 'Deposit Thickeness (mm)'"
      write(fid_script,'(g0)')"set xlabel 'Time (hours after eruption)'"
      write(fid_script,'(g0)')"set nokey"
      linebuffer080 = "set output '" // filename_png // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
      linebuffer080 = "set title '" // Airport_Name(pt_indx) // "'"
      write(fid_script,'(g0)')trim(adjustl(linebuffer080))
!      linebuffer080 = "plot [0:",ceiling(Simtime_in_hours),"][0:",&
!                      nint(ymaxpl),
      linebuffer080 = "] '" // filename_outdata // "' with filledcurve x1 ls 1"
      write(fid_script,'(a8,i5,a4,i3,a)')"plot [0:",ceiling(Simtime_in_hours),"][0:",&
                              nint(ymaxpl),trim(adjustl(linebuffer080))
      close(fid_script)

      write(plotcom,'(a11,a14)')'gnuplot -p ',filename_script
      call execute_command_line(plotcom,&
                                wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)

      ! Clean up
      if (CleanScripts_gnuplot) then
        cmd = "rm -f depTS_*.dat depTS_*.gpi"
        call execute_command_line(trim(adjustl(cmd)),&
                                  wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)
      endif

      do io=1,2;if(VB(io).le.verbosity_debug1)then
        write(outlog(io),*)"     Exited Subroutine write_DepPOI_TS_PNG_gnuplot"
      endif;enddo

      return

      end subroutine write_DepPOI_TS_PNG_gnuplot

!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

      end module Ash3d_PostProc_gnuplot

