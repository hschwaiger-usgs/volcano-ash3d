                      trim(adjustl(projX_str))    // " " // &
                      "-Cc.lev -A-"               // " " // &
                      trim(adjustl(penstr(ilev))) // " " // &
                      "-D"                        // &
                      trim(adjustl(filename_contourdata))
            endif
            write(fid_script,'(g0)')trim(adjustl(cmd))
          else
            if (IsLatLon) then
              cmd = "gmt grdcontour out.grd"      // " " // &
                      trim(adjustl(area_str))     // " " // &
                      trim(adjustl(proj_str))     // " " // &
                      "-Cc.lev -A-"               // " " // &
                      trim(adjustl(penstr(ilev))) // " " // &
                      trim(adjustl(contn_ps))
            else
              cmd = "gmt grdcontour out.grd"      // " " // &
                      trim(adjustl(projX_str))    // " " // &
                      "-Cc.lev -A-"               // " " // &
                      trim(adjustl(penstr(ilev))) // " " // &
                      trim(adjustl(contn_ps))
            endif
            write(fid_script,'(g0)')trim(adjustl(cmd))
          endif
        enddo
      endif

      ! Add cities.
      do icty=1,ncities
        write(dumstr17,'(f8.3,1x,f8.3)')lon_cities(icty),lat_cities(icty)
        cmd = "echo " // dumstr17 // " '1.0' | gmt psxy " // &
                trim(adjustl(area_str))        // " " // &
                trim(adjustl(proj_str))        // " " // &
                "-Sc0.05i -Gblack -Wthinnest"  // " " // &
                trim(adjustl(contn_ps))
        if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))
      enddo
      cmd = "gmt pstext cities.xy " // &
              trim(adjustl(area_str))  // " " // &
              trim(adjustl(proj_str))  // " " // &
              "-D0.1/0.1 -V"           // " " // &
              trim(adjustl(contn_ps))
      ! cities.xy has the following format for each line:
      !     -99.1276   19.4270  10  0  9  BL    Mexico City
      ! if this file doesn't exist for some reason, we should write equivalent commands
      ! to the script
      inquire( file="cities.xy", exist=IsThere1)
      if(IsThere1)then
        if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))
      endif

      ! Last gmt command is to plot the volcano and close out the ps file
      ! echo $VCLON $VCLAT '1.0' | ${GMTpre[GMTv]} psxy $AREA $PROJ -St0.1i -Gblack -Wthinnest -O >> temp.ps
      write(dumstr17,'(f8.3,1x,f8.3)')lon_volcano,lat_volcano
      cmd = "echo " // dumstr17 // " '1.0' | gmt psxy " // &
              trim(adjustl(area_str))  // " " // &
              trim(adjustl(proj_str))  // " " // &
              "-St0.1i -Gmagenta -Wthinnest " // &
              trim(adjustl(contn_ps))
      if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Add descriptive footer here
      !gmt pslegend leg1.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx-1.0i/-1.5i/3.0i/1.0i/BL -K -O  >> temp.ps
      cmd = "gmt pslegend leg1.txt"   // " " // &
              trim(adjustl(area_str)) // " " // &
              trim(adjustl(proj_str)) // " " // &
              "-Dx-1.0i/-1.5i/3.0i/1.0i/BL " // &
              trim(adjustl(contn_ps))
      if(.not.writeContours)write(fid_script,'(g0)') trim(adjustl(cmd))

      !gmt pslegend leg2.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx2.0i/-1.5i/4.0i/1.0i/BL -K -O  >> temp.ps
      cmd = "gmt pslegend leg2.txt"   // " " // &
              trim(adjustl(area_str)) // " " // &
              trim(adjustl(proj_str)) // " " // &
              "-Dx2.0i/-1.5i/4.0i/1.0i/BL "  // &
              trim(adjustl(contn_ps))
      if(.not.writeContours)write(fid_script,'(g0)') trim(adjustl(cmd))

      !gmt pslegend leg3.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx6.0i/-2.3i/2.0i/1.0i/BL -K -O  >> temp.ps
      inquire( file="leg3.txt", exist=IsThere1)
      if(IsThere1)then
        cmd = "gmt pslegend leg3.txt"        // " " // &
                trim(adjustl(area_str))      // " " // &
                trim(adjustl(proj_str))      // " " // &
                "-Dx6.0i/-2.3i/2.0i/1.0i/BL" // " " // &
                trim(adjustl(contn_ps))
        if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))
      endif
      ! Add contour legend here
      cmd = "gmt pslegend leg4.txt"     // " " // &
              trim(adjustl(area_str))   // " " // &
              trim(adjustl(proj_str))   // " " // &
              "-Dx8.0i/2.0i/1.25i/2.5i/BL -F " // &
              trim(adjustl(end_ps))
      if(.not.writeContours)write(fid_script,'(g0)')  trim(adjustl(cmd))

      !gmt pslegend leg4.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx8.0i/2.0i/1.25i/2.5i/BL -F -O  >> temp.ps

      ! This command converts temp.ps to temp.png
      cmd = "gmt psconvert temp.ps -A -Tg"
      if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Might need to add this check in the GMT script on version 5 vs 6 (5 needs rotation)
      !GMTv=`gmt --version | cut -c1`
      !if [ $GMTv -eq 5 ] ; then
      !  convert -rotate 90 temp.png -resize 630x500 -alpha off temp.gif
      !if [ $GMTv -eq 5 ] ; then
      cmd = "convert temp.png -resize 850x600 -alpha off temp.png"
      if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Move this png to the final filename
      cmd = "mv temp.png " // filename_png
      if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))

      close(fid_script)
      write(plotcom,'(a3,a14)')'sh ',filename_script
      call execute_command_line(plotcom,&
                                wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)

      ! Clean up
      if (CleanScripts_GMT) then
        cmd = "rm -f gmt.conf c.lev out.grd temp.ps leg*.txt outvar.dat outvar.gmt cities.xy gmt.history gmt.conf"
        do io=1,2;if(VB(io) <= verbosity_info)then
          write(outlog(io),*)"Cleaning up temporary files with command:"
          write(outlog(io),*)trim(adjustl(cmd))
        endif;enddo
        call execute_command_line(trim(adjustl(cmd)),&
                                  wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)
      endif

      ! GMT script has been run, now we need to read the contour lines if we want
      ! to write a shapefile
      do io=1,2;if(VB(io) <= verbosity_info)then
        write(outlog(io),*)'Finished running GMT script. Now processing contour files if necessary.'
      endif;enddo

      if(writeContours)then
        ContourDataNcurves(:) = 0
        do ilev=1,nConLev
          write(filename_contourdata,54) "out",ilev,".con"
          ! Read filename_contourdata
          do io=1,2;if(VB(io) <= verbosity_info)then
            write(outlog(io),*)"Now trying to read contour file and loading contour data.",&
                trim(adjustl(filename_contourdata))
          endif;enddo
          inquire( file=trim(adjustl(filename_contourdata)), exist=IsThere1)
          if(IsThere1)then
            open(unit=fid_contourdata,file=filename_contourdata,status='old')
          else
            ! File does not exist; try next contour level
            cycle
          endif
        ! In the GMT contour files, all contours of a have a header in the following
        ! format:
        !> 0.01 contour -Z0.01
        ! Each curve for that level is separated by a line containing '>'

        read(fid_contourdata,'(a80)',iostat=iostatus,iomsg=iomessage)linebuffer080
        do while(iostatus >= 0)
          ! Check if this is a header line
          read(linebuffer080,*,iostat=ioerr,iomsg=iomessage)testkey
          if(ioerr < 0)then
            ! If reading one character fails, then there is a blank line
            ! shouldn't happen with  GMT v 5 or 6
            ! Log zero contours for this level
            ioerr = -1
            ContourDataNcurves(ilev) = 0
            do io=1,2;if(VB(io) <= verbosity_debug2)then
              write(outlog(io),*)'  File exists, but has no content. Setting ncurves for this level to 0.'
            endif;enddo
            cycle

          elseif(testkey == '>')then
            ! This is a header line
            !   n it will have this format:> 0.03 contour -Z0.03
            substr_pos1 = index(linebuffer080,'contour')

            if(substr_pos1 == 0)then
              ! key > is present, but 'contour' is not
              read(fid_contourdata,'(a80)',iostat=iostatus,iomsg=iomessage)linebuffer080
              cycle
            else
