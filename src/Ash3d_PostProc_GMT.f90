        write(cstr_note,'(a45)')'WARNING: Multiple eruptions, only first given'
      endif

      !e_StartTime,e_PlumeHeight,e_Duration,e_Volume
      write(cstr_ErStartT,'(a20,a20)')'Erup. Start Time:   ',&
            HS_xmltime(SimStartHour+e_StartTime(1),BaseYear,useLeap)
      write(cstr_ErHeight,'(a20,f4.1,a3)')'Erup. Plume Height: ',e_PlumeHeight(1),' km'
      write(cstr_ErDuratn,'(a20,f4.1,a6)')'Erup. Duration:     ',e_Duration(1),' hours'
      write(cstr_ErVolume,'(a20,f8.5,a10)')'Erup. Volume:       ',e_Volume(1),' km3 (DRE)'

      write(filename_root,52)vprof_ID
 52   format('vprof_',i4.4)
      filename_outdata = trim(adjustl(filename_root)) // ".dat"
      filename_script  = trim(adjustl(filename_root)) // ".gmt"
      filename_png     = trim(adjustl(filename_root)) // ".png"

      ! Get min/max and label interval for all three axies.
      tmin=real(0,kind=ip)
      tmax=real(ceiling(time_native(ntmax)),kind=ip)
      tlab1    = 0.0_ip
      if(tmax > 240.0_ip)then
        tlabstep = 48.0_ip
      elseif(tmax > 120.0_ip)then
        tlabstep = 24.0_ip
      elseif(tmax > 30.0_ip)then
        tlabstep = 10.0_ip
      elseif(tmax > 15.0_ip)then
        tlabstep = 5.0_ip
      elseif(tmax > 6.0_ip)then
        tlabstep = 2.0_ip
      else
        tlabstep = 1.0_ip
      endif

      zmin=real(0,kind=ip)
      zmax=real(z_cc_pd(nzmax),kind=ip)
      zlab1    = 0.0_ip
      if(zmax > 30.0_ip)then
        zlabstep = 10.0_ip
      elseif(zmax > 15.0_ip)then
        zlabstep = 5.0_ip
      elseif(zmax > 6.0_ip)then
        zlabstep = 2.0_ip
      else
        zlabstep = 1.0_ip
      endif

      cloudcon_thresh_mgm3 = CLOUDCON_THRESH * KG_2_MG / KM3_2_M3  ! convert from kg/km3 to mg/m3
      cmin=real(0,kind=ip)
      cmax=real(maxval(pr_ash(:,:,vprof_ID)),kind=ip)    ! Get the max value for this profile
      cmin=real(min(cmin,cloudcon_thresh_mgm3),kind=ip)  ! Do not let cmax drop below the threshold
      if    (cmax > 4.0e4_ip)then
          clabstep = 5.0e3_ip
      elseif(cmax > 1.0e4_ip)then
          clabstep = 2.0e3_ip
      elseif(cmax > 4.0e3_ip)then
          clabstep = 5.0e2_ip
      elseif(cmax > 1.0e3_ip)then
          clabstep = 2.0e2_ip
      elseif(cmax > 4.0e2_ip)then
          clabstep = 5.0e1_ip
      elseif(cmax > 1.0e2_ip)then
          clabstep = 2.0e1_ip
      elseif(cmax > 4.0e1_ip)then
          clabstep = 5.0e0_ip
      elseif(cmax > 1.0e1_ip)then
          clabstep = 2.0e0_ip
      elseif(cmax > 1.0e0_ip)then
          clabstep = 5.0e-1_ip
      else
          clabstep = 1.0e-1_ip
      endif
      clab1    = 0.0_ip
      dtg = (tmax-tmin)/100.0_ip
      dzg = (zmax-zmin)/100.0_ip

      ! Prep data: GMT will load x y z data in column format
      open(unit=fid_outdata,file=filename_outdata,status='replace')
      do i = 1,ntmax
        do k = 1,nzmax
          write(fid_outdata,*)time_native(i),z_cc_pd(k),pr_ash(k,i,vprof_ID)
        enddo
        write(fid_outdata,'(g0)')""
      enddo
      close(fid_outdata)

      ! Build the plot title
      if(IsLatLon)then
        write(coord_str,101)x_vprofile(vprof_ID),y_vprofile(vprof_ID)
      else
        write(coord_str,102)x_vprofile(vprof_ID),y_vprofile(vprof_ID)
      endif
 101  format(' (lon=',f7.2,', lat=',f6.2,')')
 102  format(' (x=',f9.3,', y=',f9.3,')')
      write(title_plot,*)trim(adjustl(Site_vprofile(vprof_ID))),coord_str

      ! Write annotations to several legends
      !  Left panel
      open(unit=fid_misc,file="leg1.txt",status='replace')
      linebuffer080 = "T " // trim(adjustl(cstr_volcname))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_run_date))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_windfile))
      write(fid_misc,'(g0)')linebuffer080
      close(fid_misc)

      !  Right panel
      open(unit=fid_misc,file="leg2.txt",status='replace')
      linebuffer080 = "T " // trim(adjustl(cstr_ErStartT))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_ErHeight))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_ErDuratn))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_ErVolume))
      write(fid_misc,'(g0)')linebuffer080
      close(fid_misc)

      if(HaveIconFile)then
        open(unit=fid_misc,file="leg3.txt",status='replace')
        write(fid_misc,'(g0)')"I " // trim(adjustl(Instit_IconFile)) // " 2i C"
        close(fid_misc)
      endif

      ! Set up to plot via GMT script
      open(unit=fid_script,file=filename_script,status='replace')

      ! AREA string:    AREA="-R$lonmin/$lonmax/$latmin/$latmax"
      area_str = "-R0/"
      write(flt_str,'(f8.3)')tmax
      area_str = trim(area_str) // trim(adjustl(flt_str)) // "/0/"
      write(flt_str,'(f8.3)')zmax
      area_str = trim(area_str) // trim(adjustl(flt_str))

          ! Non-geographic projection, (x,y) only
      proj_str = " -JX5i/4i"

      ! Initial pscoast command to start the ps file
      start_ps = "-K > "     // trim(adjustl(filename_ps))
      contn_ps = "-K -O >> " // trim(adjustl(filename_ps))
      end_ps   = "-O >> "    // trim(adjustl(filename_ps))

      ! Set up to plot via GMT script
      write(fid_script,'(g0)')'#!/bin/bash'
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"# Temporary GMT script for producing vertical profiles for Ash3d_PostProc"
      write(fid_script,'(g0)')"# Adjust to suit your needs."
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"gmt gmtset PS_MEDIA=letter"
      ! write out to CPT.
      write(flt_str,'(f7.1)')cmax
      cmd = 'gmt makecpt -Cjet -T0/' // trim(adjustl(flt_str)) // "/0.25 > my.cpt"
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Resample profile data to regular grid
      incr_str = " -I"
      write(flt_str,'(f8.3)')dtg
      incr_str = trim(incr_str) // trim(adjustl(flt_str)) // "/"
      write(flt_str,'(f8.3)')dzg
      cmd = 'gmt surface'                     // " " // &
              trim(adjustl(filename_outdata)) // " " // &
              trim(adjustl(area_str))         // " " // &
              trim(adjustl(incr_str))         // " " // &
              '-Gout.grd'
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Make sure there are no negative concentrations (might happen from regridding)
      cmd = 'gmt grdmath out.grd 0 MAX = out.grd'
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Write basemap
      title_plot = trim(adjustl(Site_vprofile(vprof_ID))) // coord_str // '"'
      title_str  = '-B+t"' // trim(adjustl(title_plot))
      cmd = 'gmt psbasemap -X3i -Y3i'    // " " // &
              trim(adjustl(area_str))    // " " // &
              trim(adjustl(proj_str))    // " " // &
              trim(adjustl(title_str))   // " " // &
              trim(adjustl(start_ps))
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Contour data
      base_str = '-Bxa2+l"' // trim(adjustl(cstr_xlabel)) // &
                     '" -Bya2+l"' // trim(adjustl(cstr_ylabel)) // '" -BWS'
      cmd = "gmt grdimage out.grd -Cmy.cpt " // " " // &
              trim(adjustl(area_str))   // " " // &
              trim(adjustl(proj_str))   // " " // &
              trim(adjustl(base_str))    // " " // &
              trim(adjustl(contn_ps))
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Plot scalebar
      cmd = 'gmt psscale -Cmy.cpt -DDR+o1c/0c+w10c/0.5c -Baf+l"' // &
             trim(adjustl(cstr_zlabel)) // '" ' // &
            '-J -R -X0.5i -Y0.0i -DJMR' // " " // &
            trim(adjustl(contn_ps))
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Add descriptive footer here
      !gmt pslegend leg1.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx-1.0i/-1.5i/3.0i/1.0i/BL -K -O  >> temp.ps
      cmd = "gmt pslegend leg1.txt"   // " " // &
              trim(adjustl(area_str)) // " " // &
              trim(adjustl(proj_str)) // " " // &
              "-Dx-2.0i/-2.0i/3.0i/1.0i/BL " // &
              trim(adjustl(contn_ps))
      write(fid_script,'(g0)') trim(adjustl(cmd))

      !gmt pslegend leg2.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx2.0i/-1.5i/4.0i/1.0i/BL -K -O  >> temp.ps
      cmd = "gmt pslegend leg2.txt"   // " " // &
              trim(adjustl(area_str)) // " " // &
              trim(adjustl(proj_str)) // " " // &
              "-Dx1.0i/-2.0i/4.0i/1.0i/BL "  // &
              trim(adjustl(contn_ps))
      write(fid_script,'(g0)') trim(adjustl(cmd))

      !gmt pslegend leg3.txt -R-134.500/-97.500/33.500/52.500  -JM-122.117/42.933/7i -Dx6.0i/-2.3i/2.0i/1.0i/BL -K -O  >> temp.ps
      inquire( file="leg3.txt", exist=IsThere1)
      if(IsThere1)then
        cmd = "gmt pslegend leg3.txt"        // " " // &
                trim(adjustl(area_str))      // " " // &
                trim(adjustl(proj_str))      // " " // &
                "-Dx5.0i/-2.7i/2.0i/1.0i/BL" // " " // &
                trim(adjustl(end_ps))
        write(fid_script,'(g0)')trim(adjustl(cmd))
      endif

      ! This command converts temp.ps to temp.png
      cmd = "gmt psconvert temp.ps -A -Tg"
      write(fid_script,'(g0)')trim(adjustl(cmd))

      cmd = "convert temp.png -resize 850x600 -alpha off temp.png"
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Move this png to the final filename
      cmd = "mv temp.png " // filename_png
      write(fid_script,'(g0)')trim(adjustl(cmd))

      close(fid_script)
      write(plotcom,'(a3,a14)')'sh ',filename_script
      call execute_command_line(plotcom,&
                                wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)

      ! Clean up
      if (CleanScripts_GMT) then
        cmd = "rm -f gmt.conf gmt.history leg*.txt my.cpt out.grd temp.ps vprof_*.gmt vprof_*.dat"
        do io=1,2;if(VB(io) <= verbosity_info)then
          write(outlog(io),*)"Cleaning up temporary files with command:"
          write(outlog(io),*)trim(adjustl(cmd))
        endif;enddo
        call execute_command_line(trim(adjustl(cmd)),&
                                  wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)
      endif

      do io=1,2;if(VB(io) <= verbosity_debug1)then
        write(outlog(io),*)"     Exited Subroutine write_2Dprof_PNG_GMT"
      endif;enddo

      return

      end subroutine write_2Dprof_PNG_GMT

!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
!
!  write_DepPOI_TS_PNG_GMT
!
!  Called from: Ash3d_PostProc.f90
!  Arguments:
!    pt_indx       = index of point in Ash3d netcdf output file
!
!  This subroutine creates a png plot of the transient deposit accumulation at
!  the airport/POI given by pt_index using the GMT graphics package.
!
!  To invoke:
!   ASH3DPLOT=4 ./Ash3d_PostProc 3d_tephra_fall.nc 8 2
!
!   Example script:
!     #!/bin/bash
!     ##########################################################################
!     # Temporary GMT script for producing deposit time-series plots for Ash3d_PostProc
!     # Adjust to suit your needs.
!     ##########################################################################
!     gmt gmtset PS_MEDIA=300x400
!     gmt psbasemap -R/0/25.000/0/1.000 -JX4.0i/2.5i -B+t"Cuernavaca, Mexico"  -K > temp.ps
!     gmt psbasemap -R/0/25.000/0/1.000 -JX4.0i/2.5i  -Bxa$dxg+l"Time (hours after eruption)" -Bya$dyg+l"Deposit Thickness (mm)" -BWS -K -O >> temp.ps
!     gmt psxy -R/0/25.000/0/1.000 -JX4.0i/2.5i  -Ggrey -L+yb depTS_0001.dat -W0.5p -BWS -X0.0i -Y0.0i -O >> temp.ps
!     gmt psconvert temp.ps -Tg
!     convert temp.png -rotate 90 -resize 400x300 -alpha off temp.png
!     mv temp.png depTS_0001.png
!
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

      subroutine write_DepPOI_TS_PNG_GMT(pt_indx)

      use Output_Vars,   only : &
         THICKNESS_THRESH

      use Airports,      only : &
         Airport_Name,Airport_Thickness_TS

      use io_data,       only : &
         nWriteTimes,WriteTimes

      use time_data,     only : &
         Simtime_in_hours

      integer,intent(in) :: pt_indx

      real(kind=dp) :: ymaxpl
      real(kind=ip) :: dxg
      real(kind=ip) :: dyg

      character(len=40) :: title_plot
      character(len=8)  :: flt_str
      character(len=50) :: title_str
      character(len=50) :: proj_str
      character(len=50) :: area_str
      character(len=50) :: start_ps
      character(len=50) :: contn_ps
      character(len=50) :: end_ps

      character(len=16) :: filename_ps
      character(len=10) :: filename_root
      character(len=14) :: filename_script
      character(len=14) :: filename_outdata
      character(len=14) :: filename_png
      character(len=80) :: plotcom
      integer           :: i
      integer           :: iostatus
      integer           :: cstat
      character(len=120):: iomessage
      character(len=200):: cmd

      integer,save      :: plot_index = 0
      integer,parameter :: fid_script  = 55
      integer,parameter :: fid_outdata = 54

      do io=1,2;if(VB(io) <= verbosity_debug1)then
        write(outlog(io),*)"     Entered Subroutine write_DepPOI_TS_PNG_GMT"
      endif;enddo

      ! Initialization
      filename_ps  = "temp.ps"

      if(Airport_Thickness_TS(pt_indx,nWriteTimes) < THICKNESS_THRESH)then
        return
      else
        plot_index = plot_index + 1
      endif

      write(filename_root,52)plot_index
 52   format('depTS_',i4.4)
      filename_outdata = trim(adjustl(filename_root)) // ".dat"
      filename_script  = trim(adjustl(filename_root)) // ".gmt"
      filename_png     = trim(adjustl(filename_root)) // ".png"

      open(unit=fid_outdata,file=filename_outdata,status='replace')
      do i = 1,nWriteTimes
        write(fid_outdata,*)WriteTimes(i),Airport_Thickness_TS(pt_indx,i)
      enddo
      close(fid_outdata)

      if(Airport_Thickness_TS(plot_index,nWriteTimes) < THICKNESS_THRESH)then
        ymaxpl = 1.0_dp
        dyg = 0.1_ip
      elseif(Airport_Thickness_TS(plot_index,nWriteTimes) < 1.0_dp)then
        ymaxpl = 1.0_dp
        dyg = 0.1_ip
      elseif(Airport_Thickness_TS(plot_index,nWriteTimes) < 5.0_dp)then
        ymaxpl = 5.0_dp
        dyg = 0.5_ip
      elseif(Airport_Thickness_TS(plot_index,nWriteTimes) < 25.0_dp)then
        ymaxpl = 25.0_dp
        dyg = 2.0_ip
      else
        ymaxpl = 100.0_dp
        dyg = 10.0_ip
      endif

      ! Set up to plot via GMT script
      open(unit=fid_script,file=filename_script,status='replace')
      write(fid_script,'(g0)')'#!/bin/bash'
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"# Temporary GMT script for producing deposit time-series plots for Ash3d_PostProc"
      write(fid_script,'(g0)')"# Adjust to suit your needs."
      write(fid_script,'(g0)')"##########################################################################"


      title_plot = Airport_Name(pt_indx)
      title_str  = '-B+t"' // trim(adjustl(title_plot)) // '"'
      !write(title_str,*)'-B+t"',trim(adjustl(title_plot)),'"'

      ! AREA string:    AREA="-R$lonmin/$lonmax/$latmin/$latmax"
      area_str = " -R/0/"
      write(flt_str,'(f8.3)')real(ceiling(Simtime_in_hours),kind=dp)
      area_str = trim(area_str) // trim(adjustl(flt_str)) // '/0/'
      write(flt_str,'(f8.3)')real(nint(ymaxpl),kind=ip)
      area_str = trim(area_str) // trim(adjustl(flt_str))

          ! Non-geographic projection, (x,y) only
      proj_str = " -JX4.0i/2.5i"

      ! Initial pscoast command to start the ps file
      start_ps = "-K > "     // trim(adjustl(filename_ps))
      contn_ps = "-K -O >> " // trim(adjustl(filename_ps))
      end_ps   = "-O >> "    // trim(adjustl(filename_ps))

      if(ceiling(Simtime_in_hours) < 1.0_ip)then
        dxg = 0.25_ip
      elseif(ceiling(Simtime_in_hours) < 5.0_ip)then
        dxg = 0.5_ip
      elseif(ceiling(Simtime_in_hours) < 15.0_ip)then
        dxg = 1.0_ip
      elseif(ceiling(Simtime_in_hours) < 30.0_ip)then
        dxg = 5.0_ip
      elseif(ceiling(Simtime_in_hours) < 80.0_ip)then
        dxg = 10.0_ip
      else
        dxg = 25.0_ip
      endif

      write(fid_script,'(g0)')"gmt gmtset PS_MEDIA=300x400"
      cmd = "gmt psbasemap " // &
                 trim(adjustl(area_str))  // " " // &
                 trim(adjustl(proj_str))  // " " // &
                 trim(adjustl(title_str)) // " " // " " // &
                 start_ps
      write(fid_script,'(g0)')trim(adjustl(cmd))
      cmd = 'gmt psbasemap ' // &
                 trim(adjustl(area_str)) // " " // &
                 trim(adjustl(proj_str)) // " " // &
                 ' -Bxa$dxg+l"Time (hours after eruption)" -Bya$dyg+l"Deposit Thickness (mm)" -BWS' // " " // &
                 contn_ps
      write(fid_script,'(g0)')trim(adjustl(cmd))
      cmd = 'gmt psxy ' // &
                 trim(adjustl(area_str)) // " " // &
                 trim(adjustl(proj_str)) // " " // &
                 ' -Ggrey -L+yb '               // &
                 filename_outdata               // &
                 ' -W0.5p -BWS -X0.0i -Y0.0i' // " " // &
                 end_ps
      write(fid_script,'(g0)')trim(adjustl(cmd))
      cmd = "gmt psconvert temp.ps -Tg"
      write(fid_script,'(g0)')trim(adjustl(cmd))
      cmd = "convert temp.png -rotate 90 -resize 400x300 -alpha off temp.png"
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Move this png to the final filename
      cmd = "mv temp.png " // filename_png
      write(fid_script,'(g0)')trim(adjustl(cmd))

      close(fid_script)

      write(plotcom,'(a3,a14)')'sh ',filename_script
      call execute_command_line(plotcom,&
                                wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)

      ! Clean up
      if (CleanScripts_GMT) then
        cmd = "rm -f gmt.conf gmt.history temp.ps depTS_*.gmt depTS_*.dat"
        do io=1,2;if(VB(io) <= verbosity_info)then
          write(outlog(io),*)"Cleaning up temporary files with command:"
          write(outlog(io),*)trim(adjustl(cmd))
        endif;enddo
        call execute_command_line(trim(adjustl(cmd)),&
                                  wait=.true., exitstat=iostatus, cmdstat=cstat, cmdmsg=iomessage)
      endif

      do io=1,2;if(VB(io) <= verbosity_debug1)then
        write(outlog(io),*)"     Exited Subroutine write_DepPOI_TS_PNG_GMT"
      endif;enddo

      return

      end subroutine write_DepPOI_TS_PNG_GMT

