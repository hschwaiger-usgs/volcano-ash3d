          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev(1:nConLev) = Con_CloudCon_Lev(1:nConLev)
          zrgb(1:nConLev,1:3) = Con_CloudCon_RGB(1:nConLev,1:3)
        endif
      elseif(iprod == 10)then   ! ash-cloud height
        varname = "cloud_height"
        write(filename_png,'(a19,a9,a4)')'Ash3d_CloudHeight_t',cio,outfile_ext
        write(title_plot,'(a19,f7.2,a6)')'Ash-cloud height t=',WriteTimes(itime),' hours'
        cstr_zlabel = 'Cld.Height(km)'
        units = " (km)"
        Fill_Value_str = '-9999.'
        if(.not.Con_Cust)then
          nConLev = Con_CloudTop_N
          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev(1:nConLev) = Con_CloudTop_Lev(1:nConLev)
          zrgb(1:nConLev,1:3) = Con_CloudTop_RGB(1:nConLev,1:3)
        endif
      elseif(iprod == 11)then   ! ash-cloud bottom
        varname = "cloud_bottom"
        write(filename_png,'(a16,a9,a4)')'Ash3d_CloudBot_t',cio,outfile_ext
        write(title_plot,'(a19,f7.2,a6)')'Ash-cloud bottom t=',WriteTimes(itime),' hours'
        cstr_zlabel = 'Cld.Bot.(km)'
        units = " (km)"
        Fill_Value_str = '-9999.'
        if(.not.Con_Cust)then
          nConLev = Con_CloudBot_N
          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev(1:nConLev) = Con_CloudBot_Lev(1:nConLev)
          zrgb(1:nConLev,1:3) = Con_CloudBot_RGB(1:nConLev,1:3)
        endif
      elseif(iprod == 12)then   ! ash-cloud load
        varname = "cloud_load"
        write(filename_png,'(a17,a9,a4)')'Ash3d_CloudLoad_t',cio,outfile_ext
        write(title_plot,'(a17,f7.2,a6)')'Ash-cloud load t=',WriteTimes(itime),' hours'
        cstr_zlabel = 'Cld.Load(T/km2)'
        units = " (T/km2)"
        Fill_Value_str = '-9999.'
        if(.not.Con_Cust)then
          nConLev = Con_CloudLoad_N
          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev(1:nConLev) = Con_CloudLoad_Lev(1:nConLev)
          zrgb(1:nConLev,1:3) = Con_CloudLoad_RGB(1:nConLev,1:3)
        endif
      elseif(iprod == 13)then  ! radar reflectivity
        varname = "radar_reflectivity"
        write(filename_png,'(a20,a9,a4)')'Ash3d_CloudRadRefl_t',cio,outfile_ext
        write(title_plot,'(a24,f7.2,a6)')'Ash-cloud radar refl. t=',WriteTimes(itime),' hours'
        cstr_zlabel = 'Cld.Refl.(dBz)'
        units = " (dBz)"
        Fill_Value_str = '-9999.'
        if(.not.Con_Cust)then
          nConLev = Con_CloudRef_N
          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev(1:nConLev) = Con_CloudRef_Lev(1:nConLev)
          zrgb(1:nConLev,1:3) = Con_CloudRef_RGB(1:nConLev,1:3)
        endif
      elseif(iprod == 14)then   ! ashcloud arrival time (hours)
        varname = "ash_arrival_time"
        write(filename_png,'(a20)')'CloudArrivalTime.png'
        write(title_plot,'(a22)')'Ash-cloud arrival time'
        cstr_zlabel = 'Time (hours)'
        units = " (hours)"
        Fill_Value_str = '-9999.'
        if(.not.Con_Cust)then
          nConLev = Con_CloudTime_N
          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev(1:nConLev) = Con_CloudTime_Lev(1:nConLev)
          zrgb(1:nConLev,1:3) = Con_CloudTime_RGB(1:nConLev,1:3)
        endif
      elseif(iprod == 15)then   ! topography
        varname = "topography"
        write(filename_png,'(a14)')'Topography.png'
        write(title_plot,'(a10)')'Topography'
        cstr_zlabel = 'Elevation (km)'
        units = " (hours)"
        Fill_Value_str = '-9999.'
        if(.not.Con_Cust)then
          nConLev = 8
          allocate(zrgb(nConLev,3))
          allocate(ContourLev(nConLev))
          ContourLev = [1.0_ip, 2.0_ip, 3.0_ip, 4.0_ip, &
                        5.0_ip, 6.0_ip, 7.0_ip, 8.0_ip]
        endif
      elseif(iprod == 16)then   ! profile plots
        do io=1,2;if(VB(io) <= verbosity_error)then
          write(errlog(io),*)"ERROR: No map PNG output option for vertical profile data."
          write(errlog(io),*)"       Should not be in write_2Dmap_PNG_GMT"
        endif;enddo
        stop 1
      else
        do io=1,2;if(VB(io) <= verbosity_error)then
          write(errlog(io),*)"ERROR: unexpected variable"
          write(errlog(io),*)"         iprod = ",iprod
          write(errlog(io),*)"       Cannot map this variable."
        endif;enddo
        stop 1
      endif
      ! Now have string vars (varname,cstr_zlabel, etc.) and contour info (nConLev,zrgb,ContourLev)

      ! When we run this subroutine via a GMT script (as opposed to the API), we
      ! write out OutVar to an ESRI ASCII file to be read by the script
      ! Now mask out non-cloud values
      if(iprod == 10.or.&  ! CloudHeight
         iprod == 11)then  ! CloudHeightBot
        mask(1:nx,1:ny) = Mask_Cloud(1:nx,1:ny)
      elseif(iprod == 7)then  ! DepArrivalTime
        mask(1:nx,1:ny) = Mask_Deposit(1:nx,1:ny)
      elseif(iprod == 14)then
        ! cloud mask based on cloud load does not work in this case the cloud load mask
        ! is a function of time
        mask(1:nx,1:ny) = .true.
        do ii=1,nx
          do jj=1,ny
            if(CloudArrivalTime(ii,jj) < 0.0_ip)mask(ii,jj) = .false.
          enddo
        enddo
      else
        mask = .true.
      endif

      if(writeContours)then
        do io=1,2;if(VB(io) <= verbosity_info)then
          write(outlog(io),*)"Running GMT to calculate contours lines"
        endif;enddo
      else
        do io=1,2;if(VB(io) <= verbosity_info)then
          write(outlog(io),*)"Running GMT to generate contour plot"
        endif;enddo
      endif

      ! This is the section where we actually start plotting the map
      ! Evaluate grid
      if(IsLatLon)then
        if(lonUR-lonLL >= 360.0_ip)then
          lonLL = 0.0_ip
          lonUR = 360.0_ip
        endif
        xmin = lonLL
        xmax = lonUR
        ymin = latLL
        ymax = latUR
        asprat = (ymax-ymin)/(xmax-xmin)
        if(abs(dn-de) < 1.0e-4_ip)then
          IsRegGrid = .true.
        else
          IsRegGrid = .false.
        endif
      else
        xmin = xLL
        xmax = xUR
        ymin = yLL
        ymax = yUR
        asprat = (ymax-ymin)/(xmax-xmin)
        if(abs(dx-dy) < 1.0e-4_ip)then
          IsRegGrid = .true.
        else
          IsRegGrid = .false.
        endif
        call PJ_proj_inv(real(xmin,kind=dp), real(ymin,kind=dp),  &
                      A3d_iprojflag, A3d_lam0,A3d_phi0,A3d_phi1,A3d_phi2, &
                      A3d_k0,A3d_Re, &
                      olam,ophi)
        lonLL = real(olam,kind=ip)
        latLL = real(ophi,kind=ip)
        call PJ_proj_inv(real(xmax,kind=dp), real(ymax,kind=dp),  &
                      A3d_iprojflag, A3d_lam0,A3d_phi0,A3d_phi1,A3d_phi2, &
                      A3d_k0,A3d_Re, &
                      olam,ophi)
        lonUR = real(olam,kind=ip)
        latUR = real(ophi,kind=ip)
      endif

      ! write out the data in a form that GMT can read
      ! ESRI ASCII for reg grids, 3-column for irregular
      if(IsRegGrid)then
        ! If the grid is regular (dx=dy) then we can write an ESRI ASCII file and convert to grd
        ! via gmt grdconvert outvar.dat=ef out.grd
        varname = "outvar"
        call write_2D_ASCII(nx,ny,OutVar,mask,Fill_Value_str,varname)
      else
        ! Irregular grids are problematic, call special ASCII interpolator
        !call write_2D_ASCII_flt_regular(nx,ny,IsLatLon,real(xmin,kind=sp),real(ymin,kind=sp),.true., &
        !                   real(de,kind=sp),real(dn,kind=sp),Fill_Value_str,&
        !                   real(OutVar,kind=sp),filename_outdata)
        ! Alternatively, write out data in column format and have GMT handle it
!        write(filename_outdata,53) "outvar.dat"
        open(unit=fid_outdata,file=filename_outdata,status='replace')
        do ii = 1,nx
          do jj = 1,ny
            if(lon_cc_pd(1) < 180.0_ip)then
              tmp_ip = lon_cc_pd(ii)
            else
              tmp_ip = lon_cc_pd(ii)-360.0_ip
            endif
            if(abs(OutVar(ii,jj)-Fill_Value) < EPS_SMALL)then
              write(fid_outdata,*)tmp_ip,lat_cc_pd(jj),"NaN"
            else
              write(fid_outdata,*)tmp_ip,lat_cc_pd(jj),OutVar(ii,jj)
            endif
          enddo
        enddo
        close(fid_outdata)
      endif
      ! Finished temporary data file

      call citylist(1,                        &  ! 1 is for external file in GMT format
                    xmin,xmax,ymin,ymax,      &
                    ncities,                  &
                    lon_cities,               &
                    lat_cities,               &
                    name_cities)
      if(IsLatLon)then
        if(lon_volcano > xmax)lon_volcano=lon_volcano-360.0_ip
      endif
      ! Build strings with run info for legend
      ! Volcano:     Erup.start:
      ! Run date:    Plm Height:
      ! Windfile:    Duration:
      !              Volume:
      write(cstr_volcname,'(a10,a20)')'Volcano:  ' ,VolcanoName
      write(cstr_run_date,'(a10,a20)')'Run Date: ',os_time_log
      read(cdf_b3l1,*,iostat=iostatus,iomsg=iomessage) iw,iwf
      write(cstr_windfile,'(a10,i5)')'Windfile: ',iwf
      if(neruptions > 1)then
        write(cstr_note,'(a45)')'WARNING: Multiple eruptions, only first given'
      endif

      !e_StartTime,e_PlumeHeight,e_Duration,e_Volume
      write(cstr_ErStartT,'(a20,a20)')'Erup. Start Time:   ',&
            HS_xmltime(SimStartHour+e_StartTime(1),BaseYear,useLeap)
      write(cstr_ErHeight,'(a20,f4.1,a3)')'Erup. Plume Height: ',e_PlumeHeight(1),' km'
      write(cstr_ErDuratn,'(a20,f4.1,a6)')'Erup. Duration:     ',e_Duration(1),' hours'
      write(cstr_ErVolume,'(a20,f8.5,a10)')'Erup. Volume:       ',e_Volume(1),' km3 (DRE)'

      ! write contour pen specifications to strings
      do ilev=1,nConLev
        write(flt_str,'(i3)')zrgb(ilev,1)
        penstr(ilev)="-W3," // trim(adjustl(flt_str))
        legpenstr(ilev)="S 0.1i - 0.15i black 3.0p," // trim(adjustl(flt_str))
        write(flt_str,'(i3)')zrgb(ilev,2)
        penstr(ilev)= trim(penstr(ilev)) // "/" // trim(adjustl(flt_str))
        legpenstr(ilev)=trim(legpenstr(ilev)) // "/" // trim(adjustl(flt_str))
        write(flt_str,'(i3)')zrgb(ilev,3)
        penstr(ilev)= trim(penstr(ilev)) // "/" // trim(adjustl(flt_str))
        legpenstr(ilev)=trim(legpenstr(ilev)) // "/" // trim(adjustl(flt_str))
        write(flt_str,'(g10.3)')ContourLev(ilev)
        legpenstr(ilev)=trim(legpenstr(ilev)) // " 0.3i " // trim(adjustl(flt_str))
      enddo

      if(writeContours)then
        do io=1,2;if(VB(io) <= verbosity_error)then
          write(outlog(io),*)"Running GMT to calculate contours lines"
        endif;enddo
        write(filename_png,'(a14)')'tmp.png'
        allocate(ContourDataNcurves(nConLev))
        allocate(ContourDataNpoints(nConLev,CONTOUR_MAXCURVES))
        allocate(ContourDataX(nConLev,CONTOUR_MAXCURVES,CONTOUR_MAXPOINTS))
        allocate(ContourDataY(nConLev,CONTOUR_MAXCURVES,CONTOUR_MAXPOINTS))
        ContourDataNcurves(:)   = 0
        ContourDataNpoints(:,:) = 0
        ContourDataX(:,:,:)     = 0.0_ip
        ContourDataY(:,:,:)     = 0.0_ip
      else
        do io=1,2;if(VB(io) <= verbosity_error)then
          write(outlog(io),*)"Running GMT to generate contour plot"
        endif;enddo
      endif

!      write(filename_contourdata,53) "outvar.con"
!      write(filename_script,53) "outvar.gmt"
! 53   format(a10)

      ! Set up to plot via GMT script
      open(unit=fid_script,file=filename_script,status='replace')

      ! Write annotations to several legends
      !  Left panel
      open(unit=fid_misc,file="leg1.txt",status='replace')
      linebuffer080 = "T " // trim(adjustl(cstr_volcname))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_run_date))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_windfile))
      write(fid_misc,'(g0)')linebuffer080
      close(fid_misc)

      !  Right panel
      open(unit=fid_misc,file="leg2.txt",status='replace')
      linebuffer080 = "T " // trim(adjustl(cstr_ErStartT))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_ErHeight))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_ErDuratn))
      write(fid_misc,'(g0)')linebuffer080
      write(fid_misc,'(a5)')"G0.2i"
      linebuffer080 = "T " // trim(adjustl(cstr_ErVolume))
      write(fid_misc,'(g0)')linebuffer080
      close(fid_misc)

      if(HaveIconFile)then
        open(unit=fid_misc,file="leg3.txt",status='replace')
        write(fid_misc,'(g0)')"I " // trim(adjustl(Instit_IconFile)) // " 2i C"
        close(fid_misc)
      endif

      !  Contour legend
      open(unit=fid_misc,file="leg4.txt",status='replace')
      write(fid_misc,'(a7)')"C black"
      write(fid_misc,'(g0)')"H 12 1 " // trim(adjustl(cstr_zlabel))
      write(fid_misc,'(a3)')"N 1"
      do ilev=1,nConLev
        write(fid_misc,'(g0)')trim(adjustl(legpenstr(ilev)))
      enddo
      close(fid_misc)

      ! Start writing the gmt bits
      ! BASE string:
      if(lonUR-lonLL <= 2.0_ip)then
        base_str   = "-Ba0.25"
        detail_str = "-Dh"
      elseif(lonUR-lonLL <= 5.0_ip)then
        base_str   = "-Ba1"
        detail_str = "-Dh"
      elseif(lonUR-lonLL <= 10.0_ip)then
        base_str   = "-Ba2"
        detail_str = "-Dh"
      elseif(lonUR-lonLL <= 20.0_ip)then
        base_str   = "-Ba5"
        detail_str = "-Dh"
      elseif(lonUR-lonLL <= 40.0_ip)then
        base_str   = "-Ba10"
        detail_str = "-Dl"
      elseif(lonUR-lonLL <= 100.0_ip)then
        base_str   = "-Ba20"
        detail_str = "-Dl"
      else
        base_str    = "-Ba20"
        detail_str  = "-Dl"
      endif
      title_str = '-B+t"' // trim(adjustl(title_plot)) // units // '"'

      ! AREA string:    AREA="-R$lonmin/$lonmax/$latmin/$latmax"
      area_str = " -R"
      write(flt_str,'(f8.3)')lonLL
      area_str = trim(area_str) // trim(adjustl(flt_str))
      write(flt_str,'(f8.3)')latLL
      area_str = trim(area_str) // "/" // trim(adjustl(flt_str))
      write(flt_str,'(f8.3)')lonUR
      area_str = trim(area_str) // "/" // trim(adjustl(flt_str))
      write(flt_str,'(f8.3)')latUR
      area_str = trim(area_str) // "/" // trim(adjustl(flt_str)) // "r"
      area2_str = " -R"
      if(IsLatLon)then
        if(lonUR-lonLL <= 100.0_ip)then
          write(flt_str,'(f8.3)')lonLL+de*0.5_ip
          area2_str = trim(area2_str) // trim(adjustl(flt_str))
          write(flt_str,'(f8.3)')latLL+dn*0.5_ip
          area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f8.3)')lonUR-de*0.5_ip
          area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
        else
          write(flt_str,'(f8.3)')0.0_sp
          area2_str = trim(area2_str) // trim(adjustl(flt_str))
          write(flt_str,'(f8.3)')latLL+dn*0.5_ip
          area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f8.3)')360.0_sp
          area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
        endif
        write(flt_str,'(f8.3)')lonUR-de*0.5_ip
        area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
        write(flt_str,'(f8.3)')latUR-dn*0.5_ip
        area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str)) // "r"
        ! Increment string:-I0.263d/0.127d
        incr_str = " -I"
        write(flt_str,'(f8.3)')de
        incr_str = trim(incr_str) // trim(adjustl(flt_str)) // "d"
        write(flt_str,'(f8.3)')dn
        incr_str = trim(incr_str) // trim(adjustl(flt_str)) // "d"
      else
        write(flt_str,'(f8.3)')lonLL+dx*0.5_ip
        area2_str = trim(area2_str) // trim(adjustl(flt_str))
        write(flt_str,'(f8.3)')latLL+dy*0.5_ip
        area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
        write(flt_str,'(f8.3)')lonUR-dx*0.5_ip
        area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str))
        write(flt_str,'(f8.3)')latUR-dy*0.5_ip
        area2_str = trim(area2_str) // "/" // trim(adjustl(flt_str)) // "r"
        ! Increment string:-I0.263d/0.127d
        incr_str = " -I"
        write(flt_str,'(f8.3)')dx
        incr_str = trim(incr_str) // trim(adjustl(flt_str)) // "d"
        write(flt_str,'(f8.3)')dy
        incr_str = trim(incr_str) // trim(adjustl(flt_str)) // "d"
      endif

      ploth = plotw*asprat

      if (IsLatLon) then
        ! For lon/lat grids, default to a Mercator projection
        ! PROJ string:    PROJ="-JM${VCLON}/${VCLAT}/20"
        if(lonUR-lonLL <= 100.0_ip)then
          proj_str = " -JM"
        else
          proj_str = " -JQ"
        endif
        write(flt_str,'(f8.3)')lon_volcano
        proj_str = trim(proj_str) // trim(adjustl(flt_str))
        write(flt_str,'(f8.3)')lat_volcano
        proj_str = trim(proj_str) // "/" // trim(adjustl(flt_str))
        write(flt_str,'(f3.1)')plotw
        proj_str = trim(proj_str) // "/" // trim(adjustl(flt_str)) // "i"
      else
        select case (A3d_iprojflag)
        case(0)
          ! Non-geographic projection, (x,y) only
          proj_str = " -JX"
          write(flt_str,'(f3.1)')plotw
          proj_str = trim(proj_str) // trim(adjustl(flt_str)) // "i/"
          write(flt_str,'(f3.1)')ploth
          proj_str = trim(proj_str) // trim(adjustl(flt_str)) // "i"
        case(1)
          ! Polar stereographic
          ! e.g.  -JS-135/90/7i"
          proj_str= " -JS"
          write(flt_str,'(f8.1)')A3d_lam0
          proj_str=trim(proj_str) // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi0
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f3.1)')plotw
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str)) // "i"
        case(2)
          ! Albers Equal Area
          ! e.g.  -JB198.475/20.0/12c
          proj_str= " -JB"
          write(flt_str,'(f8.1)')A3d_lam0
          proj_str=trim(proj_str) // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi0
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi1
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi2
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f3.1)')plotw
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str)) // "i"
        case(3)
          ! UTM
        case(4)
          ! Lambert conformal conic
          ! e.g.  -JM198.475/20.0/12c
          proj_str= " -JL"
          write(flt_str,'(f8.1)')A3d_lam0
          proj_str=trim(proj_str) // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi0
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi1
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi2
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f3.1)')plotw
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str)) // "i"
        case(5)
          ! Mercator
          ! e.g.  -JM198.475/20.0/12c
          proj_str= " -JM"
          write(flt_str,'(f8.1)')A3d_lam0
          proj_str=trim(proj_str) // trim(adjustl(flt_str))
          write(flt_str,'(f8.1)')A3d_phi0
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str))
          write(flt_str,'(f3.1)')plotw
          proj_str=trim(proj_str) // "/" // trim(adjustl(flt_str)) // "i"
        case default
          ! No projection code provided, use non-geographic projection, (x,y) only
          proj_str = " -JX"
          write(flt_str,'(f3.1)')plotw
          proj_str = trim(proj_str) // trim(adjustl(flt_str)) // "i/"
          write(flt_str,'(f3.1)')ploth
          proj_str = trim(proj_str) // trim(adjustl(flt_str)) // "i"
        end select

        ! This is the xy grid for contours that will be overlain on the lon/lat grid
        projX_str = " -JX"
        write(flt_str,'(f3.1)')plotw
        projX_str = trim(projX_str) // trim(adjustl(flt_str)) // "i/"
        write(flt_str,'(f3.1)')ploth
        projX_str = trim(projX_str) // trim(adjustl(flt_str)) // "i"
      endif

      ! COAST string
      coast_str = " -G220/220/220 -W"

      ! RIVER string
      !if()then ! small domain, include rivers
      !  river_str = " -I1/1p,blue -I2/0.25p,blue"
      !else
        river_str = ""
      !endif

      ! Initial pscoast command to start the ps file
      start_ps = "-K > "     // trim(adjustl(filename_ps))
      contn_ps = "-K -O >> " // trim(adjustl(filename_ps))
      end_ps   = "-O >> "    // trim(adjustl(filename_ps))

      ! Set up to plot via GMT script
      write(fid_script,'(g0)')'#!/bin/bash'
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"# Temporary GMT script for producing 2d maps for Ash3d_PostProc"
      write(fid_script,'(g0)')"# Adjust to suit your needs."
      write(fid_script,'(g0)')"##########################################################################"
      write(fid_script,'(g0)')"gmt gmtset PS_MEDIA=letter"
      if(.not.writeContours)write(fid_script,'(g0)')'gmt gmtset PROJ_ELLIPSOID Sphere'
      cmd = 'gmt psbasemap -X1.5i -Y2i'  // " " // &
              trim(adjustl(area_str))    // " " // &
              trim(adjustl(proj_str))    // " " // &
              trim(adjustl(base_str))    // " " // &
              trim(adjustl(title_str))   // " " // &
              trim(adjustl(start_ps))
      if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))

      cmd = "gmt pscoast"               // " " // &
              trim(adjustl(area_str))   // " " // &
              trim(adjustl(proj_str))   // " " // &
              trim(adjustl(detail_str)) // " " // &
              trim(adjustl(coast_str))  // " " // &
              trim(adjustl(river_str))  // " " // &
              trim(adjustl(contn_ps))
      if(.not.writeContours)write(fid_script,'(g0)')trim(adjustl(cmd))

      ! Get grid to contour, converting the ASCII file generated above
      ! We need this line regardless of if we are just making contours or not
      if(IsRegGrid)then
        cmd = "gmt grdconvert " // trim(adjustl(filename_outdata)) // "=ef out.grd"
      else
        cmd = "gmt xyz2grd " // trim(adjustl(filename_outdata)) // " " // &
              trim(adjustl(area2_str)) // " " // &
              trim(adjustl(incr_str))   // " " // &
              trim(adjustl(" -Gout.grd"))
      endif
      write(fid_script,'(g0)')trim(adjustl(cmd))

      ! write contour
      if(ContourFilled)then
        ! Filled contours not yet implemented
      else
        !gmt grdcontour out.grd $AREA $PROJ $BASE -Cdpm_1.lev    -A- -W3,0/128/255   -O -K >> temp.ps
