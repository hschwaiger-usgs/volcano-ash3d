 54         format(a3,i0.2,a4)  ! write contour file name with level zero-padded
            !gmt grdcontour out.grd $AREA $PROJ $BASE -Cc.lev    -A- -W3,0/128/255 -Dcfile.xyz
!            write(fid_script,*)'echo "',real(ContourLev(i),kind=4), '   C" > c.lev'

            if (IsLatLon) then
