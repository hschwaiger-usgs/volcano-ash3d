                      trim(adjustl(area_str))     // " " // &
                      trim(adjustl(proj_str))     // " " // &
                      "-Cc.lev -A-"               // " " // &
                      trim(adjustl(penstr(ilev))) // " " // &
                      "-D"                        // &
